#include "philo.h"

long	ft_atol(const char *nptr)
{
	size_t	i;
	long	num;
	long	neg;

	i = 0;
	num = 0;
	neg = 0;
	if (!nptr || !*nptr)
		return (num);
	while ((nptr[i] >= 9 && nptr[i] <= 13) || nptr[i] == ' ')
		i++;
	if (nptr[i] == '+' || nptr[i] == '-')
	{
		if (nptr[i] == '-')
			neg = 1;
		i++;
	}
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		num = num * 10 + nptr[i] - '0';
		i++;
	}
	if (neg)
		return (-num);
	return (num);
}
